// Extracts the "Color=Off" variant of each Figma 32px weather icon set
// (assets/32/*.svg, 72×119 component-set frames) into monochrome path data.
// Off variant sits at x 20–52, y 20–52; the On variant sits below y 60.
// Output: src/icons/weather.ts (paths use currentColor).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

const dir = 'assets/32'
const toKey = (name) =>
  name.replace(/\.svg$/, '').replace(/&/g, '-and-').replace(/\s+/g, '-').toLowerCase()

const icons = {}
for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, file), 'utf8')
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  const off = paths.filter((d) => {
    const y = Number(d.match(/^M[\d.]+ ([\d.]+)/)?.[1])
    return y < 60
  })
  icons[toKey(basename(file))] = off
}

const body = Object.entries(icons)
  .map(([k, ds]) => `  '${k}': [\n${ds.map((d) => `    '${d}',`).join('\n')}\n  ],`)
  .join('\n')

writeFileSync(
  'src/icons/weather.ts',
  `// Generated by scripts/build-icons.mjs from assets/32 — do not edit.\n` +
    `// viewBox "20 20 32 32" (Figma "Color=Off" variant), fill currentColor, evenodd.\n` +
    `export const weatherPaths = {\n${body}\n} as const\n\n` +
    `export type WeatherIconName = keyof typeof weatherPaths\n`,
)
console.log(`icons: ${Object.keys(icons).length} written to src/icons/weather.ts`)
