// Generates src/styles/tokens.css from design-notes/token.json.
// Naming: Figma "group/name" → CSS "--group-name" (e.g. text/primary → --text-primary).
// Keys starting with "_" are notes and are skipped.
import { readFileSync, writeFileSync } from 'node:fs'

const tokens = JSON.parse(readFileSync('design-notes/token.json', 'utf8'))
const toVar = (...parts) => '--' + parts.join('-').replace(/[/\s]+/g, '-').toLowerCase()
const entries = (obj) => Object.entries(obj ?? {}).filter(([k]) => !k.startsWith('_'))

const lines = []
const section = (title, rows) => {
  lines.push(`  /* ${title} */`)
  for (const [name, value] of rows) lines.push(`  ${name}: ${value};`)
  lines.push('')
}

section('color', entries(tokens.color).map(([k, v]) => [toVar(k), v]))
section('radius', entries(tokens.radius).map(([k, v]) => [toVar('radius', k), `${v}px`]))
section('shadow', entries(tokens.shadow).map(([k, v]) => [toVar('shadow', k), v]))
section('font', entries(tokens.font).map(([k, v]) => [toVar('font', k), v]))
section('size', entries(tokens.size).map(([k, v]) => [toVar('size', k), `${v}px`]))
section('font size', entries(tokens.fontSize).map(([k, v]) => [toVar('font-size', k), `${v}px`]))
section('stroke', entries(tokens.stroke).map(([k, v]) => [toVar('stroke', k), `${v}px`]))

const css =
  `/* Generated by scripts/build-tokens.mjs from design-notes/token.json — do not edit. */\n` +
  `:root {\n${lines.join('\n').trimEnd()}\n}\n`

writeFileSync('src/styles/tokens.css', css)
console.log(`tokens.css: ${lines.filter((l) => l.includes(':')).length} custom properties`)
