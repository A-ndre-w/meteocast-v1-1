// Generates src/data/series.json: hourly values at the selected location (Trento) for every layer,
// over the 8-day window of the screens (Tue 13 → Tue 20 Oct 2026, now = Thu 15 13:00).
// Deterministic (seeded per layer) and pinned to the values shown in the Figma screens.
// null = no data (only inside the layer's modes/horizon or its noDataHours).
import { readFileSync, writeFileSync } from 'node:fs'

const { groups } = JSON.parse(readFileSync('src/data/layers.json', 'utf8'))
// Stations on the map (scripts/build-geo.mjs). The other stations' values are derived at runtime
// from Trento's (src/data/index.ts, stationValues).
const trento = JSON.parse(readFileSync('src/data/geo.json', 'utf8')).stations.find((s) => s.name === 'Trento')
const coords = ({ lon, lat }) => `${lat.toFixed(2)}° N, ${lon.toFixed(2)}° E`
const NOW_DAY = 2 // index of Thu 15 in the window
const NOW_HOUR = 13
const DAYS = 8

const seedOf = (s) => [...s].reduce((h, c) => (Math.imul(h ^ c.charCodeAt(0), 16777619) >>> 0), 2166136261)
const rng = (seed) => () => {
  seed = (seed + 0x6d2b79f5) >>> 0
  let t = seed
  t = Math.imul(t ^ (t >>> 15), t | 1)
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}

const decimalsFor = (unit, max) => (['%', 'cm', 'strikes', 'dBZ', 'W/m²', 'km/h'].includes(unit) || max >= 100 ? 0 : 1)

// Values visible in the Figma screens: [dayIndex, hour, value].
const anchors = {
  'rain-1h': [[1, 13, 1.8], [2, 13, 4.2]],
  'rain-1h-fc': [[3, 13, 6.5]],
  'snow-prob': [[3, 13, 15]],
  'snow-ground': [[2, 13, 5]],
}

const series = {}
for (const layer of groups.flatMap((g) => g.layers)) {
  const r = rng(seedOf(layer.id))
  const { max } = layer.scale
  const dec = decimalsFor(layer.unit, max)
  const phase = r() * Math.PI * 2
  const level = 0.15 + r() * 0.35
  const values = []
  for (let d = 0; d < DAYS; d++) {
    const dayRel = d - NOW_DAY
    const dayLevel = level * (0.6 + r() * 0.8)
    for (let h = 0; h < 24; h++) {
      const hourIndex = dayRel * 24 + (h - NOW_HOUR)
      // Availability mirrors src/data/index.ts (rule 8).
      let ok
      if (dayRel < 0) ok = layer.modes.includes('archive') && -dayRel <= layer.archiveDays
      else if (dayRel > 0) ok = layer.modes.includes('forecast') && dayRel <= layer.horizonDays
      else if (layer.interval === 'day') ok = layer.modes.includes('live')
      else ok = hourIndex < 0 ? layer.modes.includes('archive') : hourIndex === 0 ? layer.modes.includes('live') : layer.modes.includes('forecast')
      if (ok && layer.noDataHours?.some(([dd, from, to]) => dd === dayRel && h >= from && h <= to)) ok = false

      if (!ok) {
        values.push(null)
        continue
      }
      const t = layer.interval === 'day' ? d * 24 : d * 24 + h
      const wave = 0.5 + 0.5 * Math.sin(t / 7 + phase) * Math.cos(t / 17 + phase / 2)
      const v = Math.max(0, max * dayLevel * (0.4 + wave))
      values.push(Number(v.toFixed(dec)))
    }
  }
  for (const [d, h, v] of anchors[layer.id] ?? []) {
    if (layer.interval === 'day') for (let hh = 0; hh < 24; hh++) values[d * 24 + hh] = v
    else values[d * 24 + h] = v
  }
  series[layer.id] = { decimals: dec, values }
}

const out = {
  _doc: 'Generated by scripts/build-data.mjs — do not edit. values[dayIndex * 24 + hour], dayIndex 0 = window start (Tue 13 Oct 2026). null = no data.',
  start: '2026-10-13',
  // Trento replaced Rome (2026-10-21) so the portfolio before / after shows the same area as the original product.
  location: { name: 'Trento', coords: coords(trento), pin: trento.px },
  series,
}
writeFileSync('src/data/series.json', JSON.stringify(out))
console.log(`series.json: ${Object.keys(series).length} layers × ${DAYS * 24} hours`)
